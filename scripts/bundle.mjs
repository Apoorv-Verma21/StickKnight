/**
 * scripts/bundle.mjs — pack the compiled compiler into one browser file.
 *
 * The playground needs the whole pipeline running in the page, but the
 * project is plain CommonJS so that Node can run it with no ceremony. Rather
 * than add a build tool for one file, this walks the module graph from
 * dist/src/stickynight.js, wraps each module in a function, and gives them a
 * twenty-line `require` of their own.
 *
 * Only what the front door actually reaches is included, so cli.js and
 * repl.js — the two modules that use fs and readline — are left out
 * automatically rather than by a hand-maintained list.
 *
 *     node scripts/bundle.mjs
 *     -> playground/bundle.js, exposing window.Stickynight
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const source = path.join(root, "dist", "src");
const target = path.join(root, "playground", "bundle.js");

const ENTRY = "stickynight";

if (!fs.existsSync(path.join(source, "stickynight.js"))) {
  console.error("dist/src is missing — run `npm run build` first.");
  process.exit(1);
}

/** Every `require("...")` in a compiled file. */
function requiresIn(code) {
  const found = [];
  const pattern = /require\(\s*["']([^"']+)["']\s*\)/g;
  let match;
  while ((match = pattern.exec(code)) !== null) found.push(match[1]);
  return found;
}

/** Resolve "../ast" from inside "wasm/compiler" to "ast". */
function resolveId(fromId, request) {
  const dir = path.posix.dirname(fromId);
  return path.posix.normalize(path.posix.join(dir, request)).replace(/^\.\//, "");
}

const modules = new Map();
const queue = [ENTRY];

while (queue.length > 0) {
  const id = queue.shift();
  if (modules.has(id)) continue;

  const file = path.join(source, ...id.split("/")) + ".js";
  if (!fs.existsSync(file)) {
    throw new Error(`bundle: cannot find ${id} (looked for ${file})`);
  }

  const code = fs.readFileSync(file, "utf8");
  modules.set(id, code);

  for (const request of requiresIn(code)) {
    if (!request.startsWith(".")) {
      throw new Error(
        `bundle: ${id} requires the built-in module '${request}', which cannot run in a browser`
      );
    }
    queue.push(resolveId(id, request));
  }
}

const ordered = [...modules.keys()].sort();

const parts = [];
parts.push(`/* Stickynight — generated by scripts/bundle.mjs. Do not edit. */`);
parts.push(`/* Modules: ${ordered.join(", ")} */`);
parts.push(`(function () {`);
parts.push(`  "use strict";`);
parts.push(`  var definitions = {};`);
parts.push(`  var cache = {};`);
parts.push(``);
parts.push(`  function resolve(fromId, request) {`);
parts.push(`    if (request.charAt(0) !== ".") {`);
parts.push(`      throw new Error("Stickynight bundle: cannot load '" + request + "'");`);
parts.push(`    }`);
parts.push(`    var base = fromId.indexOf("/") === -1 ? [] : fromId.split("/").slice(0, -1);`);
parts.push(`    var parts = base.concat(request.split("/"));`);
parts.push(`    var out = [];`);
parts.push(`    for (var i = 0; i < parts.length; i++) {`);
parts.push(`      var piece = parts[i];`);
parts.push(`      if (piece === "" || piece === ".") continue;`);
parts.push(`      if (piece === "..") { out.pop(); continue; }`);
parts.push(`      out.push(piece);`);
parts.push(`    }`);
parts.push(`    return out.join("/");`);
parts.push(`  }`);
parts.push(``);
parts.push(`  function load(id) {`);
parts.push(`    if (cache[id]) return cache[id].exports;`);
parts.push(`    var definition = definitions[id];`);
parts.push(`    if (!definition) throw new Error("Stickynight bundle: no module '" + id + "'");`);
parts.push(`    var module = { exports: {} };`);
parts.push(`    cache[id] = module;`);
parts.push(`    definition(module.exports, function (request) {`);
parts.push(`      return load(resolve(id, request));`);
parts.push(`    }, module);`);
parts.push(`    return module.exports;`);
parts.push(`  }`);
parts.push(``);

for (const id of ordered) {
  parts.push(`  definitions[${JSON.stringify(id)}] = function (exports, require, module) {`);
  parts.push(modules.get(id).replace(/^/gm, "    ").replace(/\s+$/, ""));
  parts.push(`  };`);
  parts.push(``);
}

parts.push(`  var api = load(${JSON.stringify(ENTRY)});`);
parts.push(`  if (typeof window !== "undefined") window.Stickynight = api;`);
parts.push(`  if (typeof globalThis !== "undefined") globalThis.Stickynight = api;`);
parts.push(`})();`);
parts.push(``);

const output = parts.join("\n");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);

const kb = (output.length / 1024).toFixed(1);
console.log(
  `playground/bundle.js — ${modules.size} modules, ${kb} kB\n  ${ordered.join("\n  ")}`
);
