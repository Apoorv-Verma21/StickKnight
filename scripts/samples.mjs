/**
 * scripts/samples.mjs — turn examples/ into playground/samples.js.
 *
 * The playground's dropdown is generated from the real example files rather
 * than a second copy of them, so an example can never work on the command
 * line and be broken in the browser.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

/** Readable names for the dropdown, in the order they should appear. */
const TITLES = {
  "01-hello.sn": "Hello world",
  "02-grades.sn": "Grades — if / otherwise if",
  "03-fizzbuzz.sn": "FizzBuzz",
  "04-fibonacci.sn": "Fibonacci — two ways",
  "05-lists.sn": "Lists",
  "06-text.sn": "Text",
  "07-loops.sn": "Every kind of loop",
  "08-closures.sn": "Definitions that remember",
  "09-primes.sn": "Prime numbers",
  "10-sorting.sn": "Bubble sort",
  "11-wasm-demo.sn": "Numbers only — try the WebAssembly tab",
};

const ERROR_TITLES = {
  "symbol-comparison.sn": "Mistake: >= instead of 'is at least'",
  "bad-indent.sn": "Mistake: indentation that lines up with nothing",
  "missing-colon.sn": "Mistake: a missing colon",
  "unknown-name.sn": "Mistake: a mistyped name",
  "wrong-args.sn": "Mistake: too few inputs",
  "type-mix.sn": "Mistake: arithmetic on text",
  "index-out-of-range.sn": "Mistake: a position that is not there",
  "curly-braces.sn": "Mistake: curly braces",
  "unclosed-text.sn": "Mistake: text with no closing quote",
  "number-as-condition.sn": "Mistake: a number used as a condition",
  "runaway-recursion.sn": "Mistake: recursion that never stops",
  "endless-loop.sn": "Mistake: a loop that never ends",
  "keyword-as-name.sn": "Mistake: a keyword used as a name",
  "divide-by-zero.sn": "Mistake: dividing by zero",
  "several-mistakes.sn": "Mistake: four at once — try --check",
};

function collect(dir, titles) {
  return Object.keys(titles)
    .filter((name) => fs.existsSync(path.join(dir, name)))
    .map((name) => ({
      title: titles[name],
      file: name,
      source: fs.readFileSync(path.join(dir, name), "utf8"),
    }));
}

const examples = collect(path.join(root, "examples"), TITLES);
const errors = collect(path.join(root, "examples", "errors"), ERROR_TITLES);
const samples = [...examples, ...errors];

const missing = Object.keys(TITLES).filter(
  (name) => !fs.existsSync(path.join(root, "examples", name))
);
if (missing.length) {
  console.warn(`warning: named but not found: ${missing.join(", ")}`);
}

const body =
  "/* Stickynight — generated by scripts/samples.mjs from examples/. Do not edit. */\n" +
  "window.StickynightSamples = " +
  JSON.stringify(samples, null, 2) +
  ";\n";

const target = path.join(root, "playground", "samples.js");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, body);

console.log(
  `playground/samples.js — ${examples.length} programs and ${errors.length} broken ones`
);
