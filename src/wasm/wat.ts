/**
 * wasm/wat.ts — emit WebAssembly text format from the IR.
 *
 * This is the human-readable half of the back end and the one to show in the
 * viva: the .wat file can be read next to the Stickynight source and the
 * lowering is visible line by line. Branches are printed with both their
 * label name and their numeric depth (`br 2 (;break;)`) because the number is
 * what actually goes into the binary, and seeing the two together is the
 * quickest way to check the depth arithmetic is right.
 */

import { Instr, WasmFunction, WasmModule } from "./ir";

export function emitWat(module: WasmModule): string {
  const out: string[] = [];

  out.push(";; ---------------------------------------------------------------");
  out.push(";; Generated by the Stickynight compiler.");
  for (const note of module.notes) out.push(`;; ${note}`);
  out.push(";; ---------------------------------------------------------------");
  out.push("");
  out.push("(module");

  for (const imported of module.imports) {
    const params = imported.params.map((p) => `(param ${p})`).join(" ");
    const results = imported.results.map((r) => `(result ${r})`).join(" ");
    out.push(
      `  (import "${imported.module}" "${imported.field}" (func $${imported.name}${
        params ? " " + params : ""
      }${results ? " " + results : ""}))`
    );
  }

  if (module.globals.length) out.push("");
  for (const global of module.globals) {
    const type = global.mutable ? `(mut ${global.type})` : global.type;
    out.push(`  (global $${global.name} ${type} (${global.type}.const ${literal(global.init)}))`);
  }

  for (const fn of module.functions) {
    out.push("");
    out.push(...emitFunction(fn));
  }

  out.push("");
  for (const fn of module.functions) {
    if (fn.exported) out.push(`  (export "${fn.name}" (func $${fn.name}))`);
  }

  out.push(")");
  return out.join("\n") + "\n";
}

function emitFunction(fn: WasmFunction): string[] {
  const out: string[] = [];
  const params = fn.params.map((p) => `(param $${p.name} ${p.type})`).join(" ");
  const results = fn.results.map((r) => `(result ${r})`).join(" ");

  out.push(`  ;; ${fn.sourceName}`);
  out.push(`  (func $${fn.name}${params ? " " + params : ""}${results ? " " + results : ""}`);

  for (const local of fn.locals) {
    out.push(`    (local $${local.name} ${local.type})`);
  }
  if (fn.locals.length) out.push("");

  emitInstrs(fn.body, "    ", out);
  out.push("  )");
  return out;
}

function emitInstrs(instrs: Instr[], indent: string, out: string[]): void {
  for (const instr of instrs) {
    switch (instr.op) {
      case "block":
      case "loop": {
        const type = instr.result ? ` (result ${instr.result})` : "";
        out.push(`${indent}${instr.op} $${instr.label}${type}`);
        emitInstrs(instr.body, indent + "  ", out);
        out.push(`${indent}end`);
        break;
      }

      case "if": {
        const type = instr.result ? ` (result ${instr.result})` : "";
        out.push(`${indent}if${type}`);
        emitInstrs(instr.then, indent + "  ", out);
        if (instr.else) {
          out.push(`${indent}else`);
          emitInstrs(instr.else, indent + "  ", out);
        }
        out.push(`${indent}end`);
        break;
      }

      case "br":
      case "br_if":
        out.push(`${indent}${instr.op} ${instr.depth} (;${instr.label};)`);
        break;

      case "f64.const":
        out.push(`${indent}f64.const ${literal(instr.value)}`);
        break;

      case "i32.const":
        out.push(`${indent}i32.const ${instr.value}`);
        break;

      case "local.get":
      case "local.set":
      case "local.tee":
      case "global.get":
      case "global.set":
      case "call":
        out.push(`${indent}${instr.op} $${instr.name}`);
        break;

      default:
        out.push(`${indent}${instr.op}`);
        break;
    }
  }
}

/** WAT wants a plain decimal; keep -0, infinity and nan spelled correctly. */
function literal(value: number): string {
  if (Number.isNaN(value)) return "nan";
  if (value === Infinity) return "inf";
  if (value === -Infinity) return "-inf";
  if (Object.is(value, -0)) return "-0";
  return String(value);
}
